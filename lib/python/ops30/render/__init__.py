"""30ops render: every site-specific configuration file from one site.yaml.

render(site, sha) returns a Tree: install path -> Output, ordered by path.
The same site.yaml always gives the same bytes: no clock, no hostname,
hosts in site.yaml order. Text files start with a "generated" line that
names the 30ops version and the sha256 of site.yaml; JSON files cannot
carry one, so manifest.json lists every file with its mode, owner and
sha256. Secrets are never read: a config that has no *_file form gets an
@secret:<name> placeholder that install fills in (v0.5).

v0.3 covers everything outside docker compose and the alert rules; those
two arrive with the single compose project and threshold placeholders in
v0.4. docs/render.md lists the outputs.
"""
import hashlib
import json
import os
from dataclasses import dataclass

from .. import version

SECRET = "@secret:"


@dataclass
class Output:
    text: str
    mode: int = 0o644
    owner: str = "root:root"
    secret: bool = False


def header(sha, comment="#"):
    return f"{comment} generated by 30ops {version()} from site.yaml sha256:{sha}; do not edit\n"


def manifest(tree, sha):
    files = [{"path": p, "mode": f"{o.mode:04o}", "owner": o.owner,
              "sha256": hashlib.sha256(o.text.encode()).hexdigest(), "secret": o.secret}
             for p, o in sorted(tree.items())]
    return json.dumps({"version": 1, "tool": f"30ops {version()}", "site_sha256": sha, "files": files},
                      ensure_ascii=False, indent=2) + "\n"


def render(site, sha):
    from . import alertmanager, cron, gate, grafana, logs, nodes, prometheus
    tree = {}
    for mod in (prometheus, alertmanager, grafana, cron, logs, gate, nodes):
        for path, out in mod.render(site, sha).items():
            if path in tree:
                raise AssertionError(f"two renderers write {path}")
            tree[path] = out
    tree = dict(sorted(tree.items()))
    tree["etc/30ops/manifest.json"] = Output(manifest(tree, sha))
    return tree


def write(tree, out):
    """Write the tree under out; files not in the tree are left alone."""
    from .. import textfile
    for p, o in tree.items():
        dst = os.path.join(out, p)
        textfile.write(dst, o.text)
        os.chmod(dst, o.mode)


def site_sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()
